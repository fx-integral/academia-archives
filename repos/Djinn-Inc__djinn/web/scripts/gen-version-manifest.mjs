#!/usr/bin/env node
/**
 * Build-time SHA->version manifest.
 *
 * Iterates every vNNNN tag in the repo and writes web/public/versions.json
 * as {sha7: "vNNNN"}. The /network page uses this to map a validator's
 * reported git_sha back to the "real" tag number, so validators that pin
 * a stale VERSION file (e.g. UID 213 reporting v999 forever) still show
 * their actual running version when we can match the SHA.
 *
 * Must degrade gracefully: Vercel builds do a shallow clone with no tags,
 * and a missing manifest should never block a deploy. If any git step
 * fails we fall through to whatever mappings we already have (possibly
 * empty) and write the file anyway.
 */
import { execSync } from "node:child_process";
import { writeFileSync, existsSync, readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, "..", "..");
const outPath = join(here, "..", "public", "versions.json");

// On CI (Vercel in particular) the repo is a shallow clone with no tags
// visible. Regenerating here would overwrite the checked-in manifest with
// a near-empty one. The source-of-truth manifest is generated by whoever
// runs `npm run build` locally and commits the result; CI just serves it.
if (process.env.VERCEL || process.env.CI) {
  console.log("[versions] CI detected; using checked-in versions.json as-is");
  process.exit(0);
}

function tryRun(cmd) {
  try {
    return execSync(cmd, { cwd: repoRoot, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
  } catch (e) {
    console.warn(`[versions] skipped (\`${cmd}\` failed: ${e.message.split("\n")[0]})`);
    return "";
  }
}

const manifest = {};
let tagCount = 0;

const tagLines = tryRun("git for-each-ref --format='%(refname:short) %(objectname)' 'refs/tags/v[0-9]*' --sort=-v:refname");
const refs = tagLines
  .split("\n")
  .filter(Boolean)
  .map((l) => {
    const [tag, sha] = l.split(" ");
    return { tag, sha };
  });
tagCount = refs.length;

for (const { tag, sha } of refs) {
  manifest[sha.slice(0, 7)] = tag;
  manifest[sha] = tag;
}

// Walk every commit reachable from HEAD. `HEAD` always exists even on
// Vercel's shallow checkouts; `main` does not. Oldest-first so each
// untagged commit resolves to the most recent ancestor tag.
if (refs.length > 0) {
  const shaToTag = new Map(refs.map((r) => [r.sha, r.tag]));
  const allCommits = tryRun("git log --reverse --format=%H HEAD")
    .split("\n")
    .filter(Boolean);

  let lastKnownTag = null;
  for (const sha of allCommits) {
    const tag = shaToTag.get(sha);
    if (tag) {
      lastKnownTag = tag;
    } else if (lastKnownTag) {
      manifest[sha.slice(0, 7)] = lastKnownTag + "+";
    }
  }
}

// If we ended up with nothing useful (e.g. shallow clone with no tags),
// keep any previously-committed manifest rather than clobbering it with
// an empty object. Clients fall back to showing the reported version.
if (Object.keys(manifest).length === 0 && existsSync(outPath)) {
  try {
    const existing = JSON.parse(readFileSync(outPath, "utf8"));
    if (existing?.shas && Object.keys(existing.shas).length > 0) {
      console.log(`[versions] no git tags visible; keeping existing manifest (${Object.keys(existing.shas).length} SHAs)`);
      process.exit(0);
    }
  } catch {
    // ignore; we'll just write the empty one below
  }
}

writeFileSync(outPath, JSON.stringify({ generated_at: new Date().toISOString(), count: tagCount, shas: manifest }, null, 2));
console.log(`[versions] wrote ${Object.keys(manifest).length} SHA entries covering ${tagCount} tags to ${outPath}`);
